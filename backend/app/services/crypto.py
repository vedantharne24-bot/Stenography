"""Payload cryptography: AES-256-GCM with Argon2id key derivation, SHA-256 integrity.

No primitive is implemented here - AES-GCM comes from ``cryptography`` (OpenSSL)
and Argon2id from ``argon2-cffi`` (reference C implementation).

Envelope layout (version 1, all integers big-endian)::

    off  size  field
    0    4     magic  b"SLE1"
    4    1     kdf id (0 = raw 256-bit key, 1 = Argon2id passphrase)
    5    1     Argon2 time cost          (0 for raw keys)
    6    4     Argon2 memory cost, KiB   (0 for raw keys)
    10   1     Argon2 parallelism        (0 for raw keys)
    11   16    salt                      (zero for raw keys)
    27   12    GCM nonce (96-bit, random per encryption)
    39   n+16  ciphertext || 128-bit GCM tag

The 39-byte header is passed to GCM as associated data, so tampering with the
KDF parameters, salt or nonce makes authentication fail.

Plaintext layout (encrypted)::

    0    1     kind (1 = UTF-8 text, 2 = file)
    1    1     flags (bit0 = zlib-compressed content)
    2    2     filename length L (0 for text)
    4    L     filename (UTF-8, sanitised basename)
    4+L  32    SHA-256 of the original (uncompressed) content
    36+L ...   content (possibly compressed)
"""

from __future__ import annotations

import base64
import hashlib
from collections.abc import Callable
import re
import secrets
import struct
import time
import zlib
from dataclasses import dataclass, field
from enum import IntEnum

from argon2.low_level import Type, hash_secret_raw
from cryptography.exceptions import InvalidTag
from cryptography.hazmat.primitives.ciphers.aead import AESGCM

from app.core.config import get_settings
from app.core.errors import DecryptionFailure, ValidationFailed

MAGIC = b"SLE1"
HEADER_STRUCT = struct.Struct(">4sBBIB16s12s")
HEADER_LEN = HEADER_STRUCT.size  # 39
TAG_LEN = 16
KEY_LEN = 32  # AES-256
SALT_LEN = 16
NONCE_LEN = 12
CONTENT_HASH_LEN = 32
RAW_KEY_PREFIX = "slk1_"
MIN_PASSPHRASE_LENGTH = 8


class KdfId(IntEnum):
    RAW = 0
    ARGON2ID = 1


class PayloadKind(IntEnum):
    TEXT = 1
    FILE = 2


@dataclass(frozen=True)
class KdfParams:
    time_cost: int
    memory_kib: int
    parallelism: int

    @classmethod
    def from_settings(cls) -> KdfParams:
        s = get_settings()
        return cls(s.kdf_time_cost, s.kdf_memory_kib, s.kdf_parallelism)


@dataclass(frozen=True)
class Secret:
    """Either a passphrase (stretched with Argon2id) or a raw 256-bit key."""

    passphrase: str | None = None
    raw_key: bytes | None = None

    def __post_init__(self) -> None:
        if (self.passphrase is None) == (self.raw_key is None):
            raise ValueError("Provide exactly one of passphrase or raw_key")

    def __repr__(self) -> str:  # never print secret material
        return "Secret(passphrase=***)" if self.passphrase is not None else "Secret(raw_key=***)"


@dataclass
class EncryptionResult:
    envelope: bytes
    envelope_sha256: str
    content_sha256: str
    content_size: int
    compressed: bool
    kdf: str
    timings_ms: dict[str, float] = field(default_factory=dict)


@dataclass
class DecryptedPayload:
    kind: PayloadKind
    filename: str | None
    content: bytes
    content_sha256: str
    integrity_verified: bool
    kdf: str
    timings_ms: dict[str, float] = field(default_factory=dict)

    @property
    def text(self) -> str | None:
        if self.kind != PayloadKind.TEXT:
            return None
        return self.content.decode("utf-8", errors="replace")


# --------------------------------------------------------------------------- keys


def generate_raw_key() -> tuple[bytes, str]:
    """Return a CSPRNG 256-bit key and its portable text encoding (shown to the user once)."""
    key = secrets.token_bytes(KEY_LEN)
    return key, RAW_KEY_PREFIX + base64.urlsafe_b64encode(key).decode().rstrip("=")


def parse_raw_key(text: str) -> bytes:
    text = text.strip()
    if not text.startswith(RAW_KEY_PREFIX):
        raise ValidationFailed("Key must start with 'slk1_' (as generated by StegoLab)")
    body = text[len(RAW_KEY_PREFIX) :]
    try:
        key = base64.urlsafe_b64decode(body + "=" * (-len(body) % 4))
    except (ValueError, TypeError) as exc:
        raise ValidationFailed("Key is not valid base64url") from exc
    if len(key) != KEY_LEN:
        raise ValidationFailed("Key must decode to exactly 32 bytes")
    return key


def secret_from_user_input(secret: str) -> Secret:
    """Interpret user input: ``slk1_…`` strings are raw keys, anything else a passphrase."""
    if secret.strip().startswith(RAW_KEY_PREFIX):
        return Secret(raw_key=parse_raw_key(secret))
    if len(secret) < MIN_PASSPHRASE_LENGTH:
        raise ValidationFailed(f"Passphrase must be at least {MIN_PASSPHRASE_LENGTH} characters")
    return Secret(passphrase=secret)


def derive_key(passphrase: str, salt: bytes, params: KdfParams) -> bytes:
    return hash_secret_raw(
        secret=passphrase.encode("utf-8"),
        salt=salt,
        time_cost=params.time_cost,
        memory_cost=params.memory_kib,
        parallelism=params.parallelism,
        hash_len=KEY_LEN,
        type=Type.ID,
    )


# --------------------------------------------------------------------------- hashing


def sha256_hex(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


# --------------------------------------------------------------------------- plaintext framing

_SAFE_NAME = re.compile(r"[^A-Za-z0-9._ -]+")


def sanitize_filename(name: str | None) -> str:
    if not name:
        return ""
    base = name.replace("\\", "/").rsplit("/", 1)[-1]
    base = _SAFE_NAME.sub("_", base).strip(" .")
    return base[:120]


def _pack_plaintext(kind: PayloadKind, content: bytes, filename: str | None) -> tuple[bytes, bool]:
    digest = hashlib.sha256(content).digest()
    compressed_body = zlib.compress(content, level=9)
    use_compression = len(compressed_body) < len(content)
    body = compressed_body if use_compression else content
    name = sanitize_filename(filename).encode("utf-8") if kind == PayloadKind.FILE else b""
    head = struct.pack(">BBH", int(kind), 1 if use_compression else 0, len(name))
    return head + name + digest + body, use_compression


def _unpack_plaintext(plain: bytes) -> tuple[PayloadKind, str | None, bytes, bytes]:
    if len(plain) < 4 + CONTENT_HASH_LEN:
        raise DecryptionFailure("Decrypted payload is truncated")
    kind_raw, flags, name_len = struct.unpack(">BBH", plain[:4])
    try:
        kind = PayloadKind(kind_raw)
    except ValueError as exc:
        raise DecryptionFailure("Decrypted payload has an unknown type") from exc
    offset = 4 + name_len
    filename = plain[4:offset].decode("utf-8", errors="replace") if name_len else None
    expected = plain[offset : offset + CONTENT_HASH_LEN]
    body = plain[offset + CONTENT_HASH_LEN :]
    if flags & 1:
        try:
            body = zlib.decompress(body)
        except zlib.error as exc:
            raise DecryptionFailure("Decrypted payload could not be decompressed") from exc
    return kind, filename, body, expected


def plaintext_overhead(filename: str | None = None) -> int:
    return 4 + len(sanitize_filename(filename).encode("utf-8")) + CONTENT_HASH_LEN


def envelope_overhead(filename: str | None = None) -> int:
    """Bytes added on top of the (possibly compressed) content."""
    return HEADER_LEN + TAG_LEN + plaintext_overhead(filename)


# --------------------------------------------------------------------------- encrypt / decrypt


def encrypt_payload(
    content: bytes,
    secret: Secret,
    *,
    kind: PayloadKind = PayloadKind.TEXT,
    filename: str | None = None,
    kdf_params: KdfParams | None = None,
    progress: Callable[[str, float], None] | None = None,
) -> EncryptionResult:
    """Encrypt ``content``; ``progress(phase, ms)`` is called as each phase actually completes."""
    timings: dict[str, float] = {}
    t0 = time.perf_counter()
    if secret.passphrase is not None:
        params = kdf_params or KdfParams.from_settings()
        salt = secrets.token_bytes(SALT_LEN)
        key = derive_key(secret.passphrase, salt, params)
        kdf_id, kdf_name = KdfId.ARGON2ID, "argon2id"
    else:
        assert secret.raw_key is not None
        if len(secret.raw_key) != KEY_LEN:
            raise ValidationFailed("Raw key must be 32 bytes")
        params = KdfParams(0, 0, 0)
        salt = bytes(SALT_LEN)
        key = secret.raw_key
        kdf_id, kdf_name = KdfId.RAW, "raw-key"
    timings["key_derivation"] = (time.perf_counter() - t0) * 1000
    if progress:
        progress("key_derivation", timings["key_derivation"])

    t1 = time.perf_counter()
    plaintext, compressed = _pack_plaintext(kind, content, filename)
    nonce = secrets.token_bytes(NONCE_LEN)
    header = HEADER_STRUCT.pack(MAGIC, int(kdf_id), params.time_cost, params.memory_kib, params.parallelism, salt, nonce)
    ciphertext = AESGCM(key).encrypt(nonce, plaintext, header)
    envelope = header + ciphertext
    timings["encryption"] = (time.perf_counter() - t1) * 1000
    if progress:
        progress("encryption", timings["encryption"])

    t2 = time.perf_counter()
    envelope_hash = sha256_hex(envelope)
    content_hash = sha256_hex(content)
    timings["hashing"] = (time.perf_counter() - t2) * 1000
    return EncryptionResult(
        envelope=envelope,
        envelope_sha256=envelope_hash,
        content_sha256=content_hash,
        content_size=len(content),
        compressed=compressed,
        kdf=kdf_name,
        timings_ms=timings,
    )


def parse_header(envelope: bytes) -> tuple[KdfId, KdfParams, bytes, bytes]:
    if len(envelope) < HEADER_LEN + TAG_LEN:
        raise DecryptionFailure("Envelope is too short to be valid")
    magic, kdf_raw, t_cost, m_kib, par, salt, nonce = HEADER_STRUCT.unpack(envelope[:HEADER_LEN])
    if magic != MAGIC:
        raise DecryptionFailure("Envelope magic mismatch - not a StegoLab payload")
    try:
        kdf_id = KdfId(kdf_raw)
    except ValueError as exc:
        raise DecryptionFailure("Unknown key-derivation scheme") from exc
    if kdf_id == KdfId.ARGON2ID:
        # Refuse absurd parameters from an untrusted header (DoS guard).
        if not (1 <= t_cost <= 10 and 8 * 1024 <= m_kib <= 1024 * 1024 and 1 <= par <= 16):
            raise DecryptionFailure("Envelope declares out-of-range KDF parameters")
    return kdf_id, KdfParams(t_cost, m_kib, par), salt, nonce


def decrypt_envelope(envelope: bytes, secret: Secret) -> DecryptedPayload:
    timings: dict[str, float] = {}
    kdf_id, params, salt, nonce = parse_header(envelope)
    t0 = time.perf_counter()
    if kdf_id == KdfId.ARGON2ID:
        if secret.passphrase is None:
            raise DecryptionFailure("This payload was sealed with a passphrase, not a generated key")
        key = derive_key(secret.passphrase, salt, params)
        kdf_name = "argon2id"
    else:
        if secret.raw_key is None:
            raise DecryptionFailure("This payload was sealed with a generated key (slk1_…), not a passphrase")
        key = secret.raw_key
        kdf_name = "raw-key"
    timings["key_derivation"] = (time.perf_counter() - t0) * 1000

    t1 = time.perf_counter()
    try:
        plaintext = AESGCM(key).decrypt(nonce, envelope[HEADER_LEN:], envelope[:HEADER_LEN])
    except InvalidTag as exc:
        raise DecryptionFailure("Authentication failed: wrong key/passphrase or the payload was modified") from exc
    timings["decryption"] = (time.perf_counter() - t1) * 1000

    kind, filename, content, expected = _unpack_plaintext(plaintext)
    actual = hashlib.sha256(content).digest()
    verified = secrets.compare_digest(actual, expected)
    if not verified:
        raise DecryptionFailure("Inner SHA-256 mismatch: payload content is corrupted")
    return DecryptedPayload(
        kind=kind,
        filename=filename,
        content=content,
        content_sha256=actual.hex(),
        integrity_verified=verified,
        kdf=kdf_name,
        timings_ms=timings,
    )
