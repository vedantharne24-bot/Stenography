"""Build the bundled demo carriers from public-domain / CC0 photographs.

    backend/.venv/Scripts/python scripts/build_demo_carriers.py

The full held-out test split (DIV2K + COCO crops) is not redistributed with the repository.
So that a fresh clone can run the live demo and the research experiments without
downloading anything, this script cuts grid-aligned 256x256 crops (and their mirror images)
from photographs that scikit-image ships with explicit public-domain / CC0 terms. None of
these images were used to train the models. Output: backend/demo_carriers/*.png + SOURCES.md.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
from PIL import Image
from skimage import data

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "backend" / "demo_carriers"
TILE = 256

SOURCES = {
    "astronaut": ("NASA - Eileen Collins", "public domain"),
    "coffee": ("Rachel Michetti, courtesy of Pikolo Espresso Bar", "CC0"),
    "chelsea": ("Stefan van der Walt", "CC0"),
    "rocket": ("SpaceX", "public domain"),
    "hubble_deep_field": ("NASA / Hubble", "public domain"),
    "immunohistochemistry": ("scikit-image sample data", "no known copyright restrictions"),
}


def crops(rgb: np.ndarray) -> list[np.ndarray]:
    h, w = rgb.shape[:2]
    out = []
    for y in range(0, h - TILE + 1, TILE):
        for x in range(0, w - TILE + 1, TILE):
            out.append(np.ascontiguousarray(rgb[y : y + TILE, x : x + TILE]))
    return out


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("*.png"):
        old.unlink()
    lines = [
        "# Demo carriers",
        "",
        "Grid-aligned 256x256 crops (plus horizontal mirrors) of photographs distributed with",
        "scikit-image under public-domain or CC0 terms. Generated by `scripts/build_demo_carriers.py`.",
        "They were **not** used to train any model, so they are valid held-out images for the live",
        "demo and the research experiments when the full DIV2K/COCO test split is not present.",
        "",
        "| Source image | Author | Terms | Crops |",
        "|---|---|---|---|",
    ]
    total = 0
    for name, (author, terms) in SOURCES.items():
        rgb = np.asarray(getattr(data, name)())
        if rgb.ndim != 3:
            continue
        rgb = rgb[..., :3]
        tiles = crops(rgb)
        for i, tile in enumerate(tiles):
            Image.fromarray(tile).save(OUT / f"demo_{name}_{i:02d}.png", optimize=True)
            Image.fromarray(np.ascontiguousarray(tile[:, ::-1])).save(OUT / f"demo_{name}_{i:02d}m.png", optimize=True)
        total += 2 * len(tiles)
        lines.append(f"| `{name}` | {author} | {terms} | {2 * len(tiles)} |")
    (OUT / "SOURCES.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {total} carriers to {OUT}")


if __name__ == "__main__":
    main()
