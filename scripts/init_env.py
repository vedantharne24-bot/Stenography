"""Create ``backend/.env`` with strong random secrets (idempotent: never overwrites).

Usage:
    python scripts/init_env.py                 # SQLite development database
    python scripts/init_env.py --postgres      # also generate scripts/setup_postgres.sql

With ``--postgres`` a dedicated role ``stegolab`` gets a random password that is
written only to ``backend/.env`` and ``scripts/setup_postgres.sql`` (both git-ignored).
Run the SQL once as the postgres superuser:
    psql -U postgres -h localhost -f scripts/setup_postgres.sql
"""

from __future__ import annotations

import argparse
import secrets
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ENV_PATH = ROOT / "backend" / ".env"
SQL_PATH = ROOT / "scripts" / "setup_postgres.sql"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--postgres", action="store_true", help="configure a local PostgreSQL database")
    parser.add_argument("--admin-email", default="admin@stegolab.local")
    args = parser.parse_args()

    if ENV_PATH.exists():
        if args.postgres and "postgresql" not in ENV_PATH.read_text(encoding="utf-8"):
            # Setup already ran on SQLite: add PostgreSQL credentials, keep the existing secrets.
            db_password = secrets.token_urlsafe(24)
            with ENV_PATH.open("a", encoding="utf-8") as fh:
                fh.write("\n".join(_postgres_env_lines(db_password)) + "\n")
            _write_postgres_sql(db_password)
            print(f"Added a commented PostgreSQL DATABASE_URL to {ENV_PATH} and wrote {SQL_PATH}")
            return
        print(f"{ENV_PATH} already exists - leaving it untouched.")
        return

    lines = [
        "# Generated by scripts/init_env.py - never commit this file.",
        "APP_ENV=development",
        f"SECRET_KEY={secrets.token_urlsafe(48)}",
        f"JWT_SECRET={secrets.token_urlsafe(48)}",
        "COOKIE_SECURE=false",
        "MAX_UPLOAD_SIZE=20971520",
        "TEMP_RETENTION_HOURS=24",
        "DEVICE=auto",
        f"BOOTSTRAP_ADMIN_EMAIL={args.admin_email}",
        f"BOOTSTRAP_ADMIN_PASSWORD={secrets.token_urlsafe(12)}-Aa1!",
    ]

    if args.postgres:
        db_password = secrets.token_urlsafe(24)
        lines.extend(_postgres_env_lines(db_password))
        _write_postgres_sql(db_password)
        print(f"Wrote {SQL_PATH}")
    else:
        lines.append("# DATABASE_URL defaults to SQLite at backend/storage/stegolab.db")

    ENV_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {ENV_PATH} (bootstrap admin credentials are stored there)")


def _postgres_env_lines(db_password: str) -> list[str]:
    return [
        "# Uncomment after running scripts/setup_postgres.sql, then: alembic upgrade head",
        f"# DATABASE_URL=postgresql+psycopg://stegolab:{db_password}@localhost:5432/stegolab",
    ]


def _write_postgres_sql(db_password: str) -> None:
    SQL_PATH.write_text(
        "-- Generated by scripts/init_env.py. Run once as the postgres superuser:\n"
        "--   psql -U postgres -h localhost -f scripts/setup_postgres.sql\n"
        f"CREATE ROLE stegolab WITH LOGIN PASSWORD '{db_password}';\n"
        "CREATE DATABASE stegolab OWNER stegolab ENCODING 'UTF8';\n"
        "REVOKE ALL ON DATABASE stegolab FROM PUBLIC;\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
